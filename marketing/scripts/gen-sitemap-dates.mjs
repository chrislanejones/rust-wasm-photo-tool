#!/usr/bin/env node
// Writes src/data/source-dates.json: the last-commit date of every file a page
// or post names in its `sources` (seo.ts, data/posts.ts). The prerender reads it
// for the sitemap's `lastmod`.
//
// Run it as part of the release routine, from anywhere:
//
//   node marketing/scripts/gen-sitemap-dates.mjs
//
// gen-trail-data.mjs runs it too, so the routine's existing step covers it.
//
// ── why the dates are committed rather than read at build time ────────────
// The prerender used to ask git directly, and on a full clone that is right.
// Vercel does not build from a full clone. Its checkout is shallow, and the
// prerender correctly refuses a date that comes from the shallow boundary (see
// `lastCommitDate` in prerender.mjs), so in production it knew nothing older
// than the last few commits. Measured 2026-09-25: the live sitemap carried
// `lastmod` on 2 of its 24 URLs while a full clone dated all 24. Refusing the
// boundary date was the right call; this file is where the real date comes from
// instead. The prerender still prefers git whenever git gives a real answer.
//
// ── files changed but not yet committed ───────────────────────────────────
// The routine runs this BEFORE the release commit, so a page edited in that
// commit has no commit of its own yet. It gets today's date: the commit about
// to land will carry it, and the file is regenerated on the next release anyway.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const src = (p) => resolve(here, "..", "src", p);
const git = (...args) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();

// The `sources: [ "…", "…" ]` lists, read as text. Importing seo.ts would mean a
// TypeScript loader for one array; every entry is a string literal, so the text
// is the data.
const paths = new Set();
for (const file of ["seo.ts", "data/posts.ts"]) {
  const text = readFileSync(src(file), "utf8");
  for (const [, body] of text.matchAll(/sources:\s*\[([\s\S]*?)\]/g)) {
    for (const [, p] of body.matchAll(/"([^"]+)"/g)) paths.add(p);
  }
}

// If the history this runs on is shallow, the dates are the boundary's and
// worth nothing. Say so and stop rather than write them.
if (git("rev-parse", "--is-shallow-repository") === "true") {
  console.error("gen-sitemap-dates: shallow clone, refusing to write boundary dates. Run it from a full clone.");
  process.exit(1);
}

const today = new Date().toLocaleDateString("en-CA"); // YYYY-MM-DD, local calendar
const dirty = new Set(git("diff", "HEAD", "--name-only").split("\n").filter(Boolean));

const dates = {};
const missing = [];
for (const p of [...paths].sort()) {
  const committed = git("log", "-1", "--format=%cs", "--", p);
  const date = dirty.has(p) ? today : committed;
  if (date) dates[p] = date;
  else missing.push(p);
}

writeFileSync(
  src("data/source-dates.json"),
  JSON.stringify({ _generated: "GENERATED by marketing/scripts/gen-sitemap-dates.mjs. Do not edit.", dates }, null, 2) + "\n",
);

const newest = Object.values(dates).sort().at(-1);
console.log(`gen-sitemap-dates: ${Object.keys(dates).length} source files dated, newest ${newest}`);
if (missing.length) console.warn(`  no date for: ${missing.join(", ")}`);
