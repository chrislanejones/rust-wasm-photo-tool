#!/usr/bin/env node
// This site's own tokens, read out of `src/tokens.css` for the Marketing tab of
// /design-system. tokens.css is authoritative; this copies what it says into
// `src/data/siteTokens.ts` so the page can print each value as text.
//
//   pnpm -C marketing run gen:tokens
//
// A copy can go stale, so it is checked: `app/src/lib/editorTokens.drift.test.ts`
// (in CI with the app suite) re-runs `renderSiteTokens` on the live stylesheet
// and fails if the committed file says anything else.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

/** Every `--name: value;` in the `:root` block, in file order, comments dropped. */
export function parseSiteTokens(css) {
  const start = css.indexOf(":root {");
  if (start < 0) throw new Error("no :root block in tokens.css");
  let depth = 0;
  let i = css.indexOf("{", start);
  const from = i + 1;
  for (; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) break;
  }
  const body = css.slice(from, i).replace(/\/\*[\s\S]*?\*\//g, "");
  const out = {};
  for (const m of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    out[m[1]] = m[2].replace(/\s+/g, " ").replace(/\(\s+/g, "(").replace(/\s+\)/g, ")").trim();
  }
  return out;
}

/** The generated module's exact text. */
export function renderSiteTokens(css) {
  return (
    "// GENERATED by marketing/scripts/gen-site-tokens.mjs from marketing/src/tokens.css.\n" +
    "// Do not edit by hand: change tokens.css, then `pnpm -C marketing run gen:tokens`.\n" +
    "// app/src/lib/editorTokens.drift.test.ts fails when this file and the stylesheet disagree.\n" +
    `export const SITE_TOKENS: Record<string, string> = ${JSON.stringify(parseSiteTokens(css), null, 2)};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = readFileSync(join(here, "../src/tokens.css"), "utf8");
  const out = join(here, "../src/data/siteTokens.ts");
  writeFileSync(out, renderSiteTokens(css));
  console.log(`siteTokens.ts  ${Object.keys(parseSiteTokens(css)).length} tokens from src/tokens.css`);
}
