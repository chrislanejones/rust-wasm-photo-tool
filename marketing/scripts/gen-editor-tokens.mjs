#!/usr/bin/env node
// The editor's color tokens, read out of the editor's own stylesheet for the
// /design-system page. `app/src/styles.css` is authoritative; this only copies
// what it says into `src/data/editorTokens.ts`, so the marketing build never
// reaches outside `marketing/` (Vercel builds it with that as the root).
//
//   pnpm -C marketing run gen:tokens
//
// A copy can go stale, so it is checked: `app/src/lib/editorTokens.drift.test.ts`
// (in CI with the app suite) re-runs `renderEditorTokens` on the live
// stylesheet and fails if the committed file says anything else.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

/** `--name: value;` pairs of the first block opened by `selector`. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`no ${selector} block in styles.css`);
  let depth = 0;
  let i = css.indexOf("{", start);
  const from = i + 1;
  for (; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) break;
  }
  const body = css.slice(from, i).replace(/\/\*[\s\S]*?\*\//g, "");
  const out = {};
  for (const m of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

/** Follow `var(--x)` until it is a real value. */
function resolve(vars, value, depth = 0) {
  const m = /^var\(--([a-z0-9-]+)\)$/.exec(value);
  if (!m || depth > 8) return value;
  return vars[m[1]] === undefined ? value : resolve(vars, vars[m[1]], depth + 1);
}

/** Every color token the page shows, light and dark, resolved. */
export function parseEditorTokens(css) {
  const light = block(css, ":root");
  const dark = { ...light, ...block(css, ".dark") };
  const pick = (vars) =>
    Object.fromEntries(
      Object.keys(vars)
        .filter((k) => /^#|^rgba?\(|^var\(/.test(vars[k]) && !k.startsWith("shadow") && !k.startsWith("overlay"))
        .map((k) => [k, resolve(vars, vars[k])])
        .filter(([, v]) => /^#|^rgba?\(/.test(v)),
    );
  return {
    light: pick(light),
    dark: pick(dark),
    radius: { sm: "4px", md: light.radius, lg: light["radius-lg"] },
    fonts: { sans: light["font-sans"], mono: light["font-mono"] },
  };
}

/** The generated module's exact text. */
export function renderEditorTokens(css) {
  const t = parseEditorTokens(css);
  return (
    "// GENERATED by marketing/scripts/gen-editor-tokens.mjs from app/src/styles.css.\n" +
    "// Do not edit by hand: change the editor's stylesheet, then `pnpm -C marketing run gen:tokens`.\n" +
    "// app/src/lib/editorTokens.drift.test.ts fails when this file and the stylesheet disagree.\n" +
    `export const EDITOR_TOKENS = ${JSON.stringify(t, null, 2)} as const;\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = readFileSync(join(here, "../../app/src/styles.css"), "utf8");
  const out = join(here, "../src/data/editorTokens.ts");
  writeFileSync(out, renderEditorTokens(css));
  console.log(`wrote ${out}`);
}
